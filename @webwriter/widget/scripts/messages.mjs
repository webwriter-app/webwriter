// The catalogs of module text: messages/<module>/<locale>.ts, one file per
// module and language, beside the module's table in messages/<module>/index.ts.
//
//   node scripts/messages.mjs tables   writes messages/<module>/catalogs.ts, the loader of every catalog file
//   node scripts/messages.mjs check    verifies the built catalogs against their tables (run the build first)
//
// `npm run build` does both. A catalog file imports types only and
// default-exports `{…} satisfies Catalog<…Messages>` with every key of the
// table: a string where the table has a string, and a function of no more
// parameters where it has a function. The types of the parameters are checked
// by `npm run typecheck`.
import {existsSync, readdirSync, readFileSync, writeFileSync} from "node:fs"
import {dirname, join, relative} from "node:path"
import {fileURLToPath, pathToFileURL} from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const messages = join(root, "messages")
const modules = readdirSync(messages, {withFileTypes: true}).filter(entry => entry.isDirectory()).map(entry => entry.name).sort()
const reserved = new Set(["index", "catalogs"])

/** The locales a module has a catalog file for, by the names of its files. */
const localesOf = module => readdirSync(join(messages, module))
  .filter(file => file.endsWith(".ts") && !file.endsWith(".d.ts"))
  .map(file => file.slice(0, -3))
  .filter(name => !reserved.has(name))
  .sort()

/** The name of the table's type, as messages/<module>/index.ts exports it. */
function typeOf(module) {
  const names = [...readFileSync(join(messages, module, "index.ts"), "utf8").matchAll(/^export type (\w+Messages)\b/gm)].map(match => match[1])
  if(names.length !== 1) throw new Error(`messages/${module}/index.ts must export exactly one type named …Messages`)
  return names[0]
}

function tableSource(module) {
  const locales = localesOf(module)
  const key = locale => /^[a-z]+$/.test(locale) ? locale : JSON.stringify(locale)
  return [
    "// Generated by scripts/messages.mjs from the catalog files of this folder. Do not edit.",
    `import type {CatalogLoaders} from "../../messages.js"`,
    `import type {${typeOf(module)}} from "./index.js"`,
    "",
    "export default {",
    ...locales.map(locale => `  ${key(locale)}: () => import("./${locale}.js"),`),
    `} satisfies CatalogLoaders<${typeOf(module)}>`,
    "",
  ].join("\n")
}

function tables() {
  for(const module of modules) {
    const file = join(messages, module, "catalogs.ts")
    const source = tableSource(module)
    if(existsSync(file) && readFileSync(file, "utf8") === source) continue
    writeFileSync(file, source)
    console.log(`wrote ${relative(root, file)}`)
  }
}

async function check() {
  const problems = []
  let count = 0
  for(const module of modules) {
    const folder = join(messages, module)
    const fail = (file, problem) => problems.push(`messages/${module}/${file}: ${problem}`)
    if(readFileSync(join(folder, "catalogs.ts"), "utf8") !== tableSource(module)) fail("catalogs.ts", "is out of date: run `node scripts/messages.mjs tables`")
    const load = async file => {
      if(!existsSync(join(folder, file))) return void fail(file, "is not built: run `npm run build`")
      return import(pathToFileURL(join(folder, file)).href)
    }
    const sources = Object.values(await load("index.js") ?? {}).filter(value => value && typeof value === "object" && "defaults" in value && "locales" in value)
    if(sources.length !== 1) {
      fail("index.ts", "must export exactly one table made by defineMessages()")
      continue
    }
    const [{defaults, locales: declared}] = sources
    const locales = localesOf(module)
    if(declared.join() !== locales.join()) fail("index.ts", `the table loads ${declared.join(", ") || "nothing"}, but the files are ${locales.join(", ") || "none"}`)
    for(const locale of locales) {
      const file = `${locale}.ts`
      count++
      let canonical
      try { [canonical] = Intl.getCanonicalLocales(locale) }
      catch { /* reported below */ }
      if(canonical !== locale) fail(file, `"${locale}" is not a canonical language tag${canonical ? `: name the file ${canonical}.ts` : ""}`)
      const source = readFileSync(join(folder, file), "utf8")
      const imported = [...source.matchAll(/^\s*import\s+(?!type\b)[^\n]*/gm)].map(match => match[0].trim())
      if(imported.length) fail(file, `imports a value (${imported[0]}): a catalog imports types only`)
      if(!/\bsatisfies\s+Catalog</.test(source)) fail(file, "must end with `satisfies Catalog<…Messages>`, so that its entries are type-checked")
      const catalog = (await load(`${locale}.js`))?.default
      if(!catalog) continue
      if(typeof catalog !== "object") {
        fail(file, "must default-export the catalog object")
        continue
      }
      for(const key of Object.keys(catalog)) if(!Object.hasOwn(defaults, key)) fail(file, `unknown key "${key}"`)
      for(const [key, original] of Object.entries(defaults)) {
        if(!Object.hasOwn(catalog, key)) {
          fail(file, `missing key "${key}"`)
          continue
        }
        const translated = catalog[key]
        if(typeof translated !== typeof original) fail(file, `"${key}" must be a ${typeof original}, as in the table, not a ${typeof translated}`)
        else if(typeof translated === "function" && translated.length > original.length) fail(file, `"${key}" takes ${translated.length} parameters, the table gives ${original.length}`)
        else if(typeof translated === "string" && !translated.trim() && original.trim()) fail(file, `"${key}" is empty`)
      }
    }
  }
  for(const problem of problems) console.error(`FAIL  ${problem}`)
  console.log(problems.length ? `${problems.length} problems in the message catalogs` : `${count} catalogs of ${modules.length} modules match their tables`)
  process.exit(problems.length ? 1 : 0)
}

const command = process.argv[2]
if(command === "tables") tables()
else if(command === "check") await check()
else {
  console.error("usage: node scripts/messages.mjs tables | check")
  process.exit(1)
}
