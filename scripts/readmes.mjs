// Writes the README.md of each helper library from the widget reference, so that the
// two say the same. Edit the reference, then run `node scripts/readmes.mjs`.
// `node scripts/readmes.mjs --check` writes nothing and fails if a README differs.
//
// A README is the text of its part of the reference with two changes that its place
// requires: the title loses the number of the reference chapter, and a link to another
// page of the documentation points at that page from the package folder.
import {readFileSync, writeFileSync, existsSync} from "node:fs"
import {dirname, join, posix} from "node:path"
import {fileURLToPath} from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const reference = "@webwriter/domeditor/docs/widgets/reference"
const read = file => readFileSync(join(root, reference, file), "utf8")

/** The block of one library in adapters.md and the sections after the last block, which hold for every library. */
function adapter(library) {
  const source = read("adapters.md")
  const block = new RegExp(`^<!-- library:${library} -->\\r?\\n([\\s\\S]*?)^<!-- /library -->$`, "m").exec(source)
  if(!block) throw new Error(`adapters.md has no block for ${library}`)
  const close = "<!-- /library -->"
  const shared = source.slice(source.lastIndexOf(close) + close.length)
  return `${block[1].trimEnd()}\n\n${shared.trim()}\n`
}

const sources = {
  build: ["build-test.md", () => read("build-test.md")],
  lit: ["lit.md", () => read("lit.md")],
  widget: ["adapters.md", () => adapter("vanilla")],
  react: ["adapters.md", () => adapter("react")],
  vue: ["adapters.md", () => adapter("vue")],
  angular: ["adapters.md", () => adapter("angular")],
  svelte: ["adapters.md", () => adapter("svelte")],
}

/** Rewrites what depends on where the text is read. Code blocks stay as they are. */
function placed(text) {
  const toReference = posix.join("..", "domeditor/docs/widgets/reference")
  return text
    .split(/^(```[\s\S]*?^```$)/m)
    .map((part, index) => index % 2
      ? part
      : part
        .replace(/^# [A-Z]\d+\. /m, "# ")
        .replace(/\]\((?![a-z][a-z+.-]*:|#|\/)([^)\s]+)\)/g, (_, target) => `](${posix.join(toReference, target)})`))
    .join("")
}

const check = process.argv.includes("--check")
let stale = 0
for(const [name, [file, text]] of Object.entries(sources)) {
  const path = join(root, "@webwriter", name, "README.md")
  const readme = `<!-- Generated by scripts/readmes.mjs from ${reference}/${file}. Edit the reference, not this file. -->\n${placed(text())}`
  if(existsSync(path) && readFileSync(path, "utf8") === readme) continue
  stale++
  if(check) console.error(`@webwriter/${name}/README.md differs from the reference`)
  else {
    writeFileSync(path, readme)
    console.log(`wrote @webwriter/${name}/README.md`)
  }
}
if(check && stale) process.exit(1)
if(!stale) console.log("every README matches the reference")
